# Rescaled to one SD of the PARENT measure (sd_scale_of maps every split variant
# back to the variable it came from). Scaling each component by its own SD would
# be misleading, because a masked variable's SD is driven by the on/off switching
# of the mask rather than by wind; the parent's SD keeps one interpretable unit
# across a split and makes the three measures comparable to each other.

decomp <- bind_rows(
  d2 %>% filter(grepl("split", spec)) %>% mutate(block = "TC months vs the rest"),
  d3 %>% mutate(block = "TC season vs the rest"),
  d4 %>% mutate(block = "TC states vs states with no TCs")
) %>%
  mutate(base     = sub("_(tc|notc|seas|off)$", "", measure),
         sd_scale = sd_scale_of(measure),
         cum      = cum * sd_scale,
         cum_se   = cum_se * sd_scale)

part_lab <- c(
  windmax_area_month_tc = "in TC months", windmax_area_month_notc = "in non-TC months",
  w_exc_tc = "in TC months", w_exc_notc = "in non-TC months",
  windmax_area_month_seas = "Jun-Nov", windmax_area_month_off = "Dec-May",
  w_exc_seas = "Jun-Nov", w_exc_off = "Dec-May",
  maxs_seas = "Jun-Nov", maxs_off = "Dec-May")
decomp <- decomp %>%
  mutate(part = part_lab[measure],
         part = if_else(is.na(part),
                        if_else(grepl("no-TC states", spec),
                                "states with no TCs", "TC states"),
                        part))
# same factor order (and therefore same colours) as every other figure in the deck
MLAB <- c(maxs = "maxs", windmax_area_month = "ERA5 raw", w_exc = "ERA5 exceedance")
decomp <- decomp %>%
  mutate(base_lab = factor(MLAB[base], levels = MLAB)) %>%
  filter(!is.na(base_lab))
decomp <- mutate(decomp, block = factor(block, levels = c("TC months vs the rest", "TC season vs the rest",
                                                         "TC states vs states with no TCs")))

p_dec <- ggplot(decomp, aes(cum, part, colour = base_lab)) +
