# --- jackknife: express each refit as % deviation from the full-sample estimate
jk <- bind_rows(
  loo_state %>% transmute(measure, cum, t, dropped, unit = state_abbrev) %>%
    left_join(transmute(base, measure, b = cum), by = "measure") %>%
    mutate(kind = "Leave one state out"),
  loo_year %>% transmute(measure, cum, t, dropped, unit = as.character(dropped)) %>%
    left_join(transmute(base, measure, b = cum), by = "measure") %>%
    mutate(kind = "Leave one year out")
)
jk <- jk %>% mutate(dev  = 100 * (cum - b) / b,
                    mlab = factor(MLAB[measure], levels = MLAB))

p_jk <- ggplot(jk, aes(dev, mlab, colour = mlab)) +
