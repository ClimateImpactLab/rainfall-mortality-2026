#========================================================================================#
#' Why are the ERA5-Land coefficients larger than the Young-Hsiang ones?
#'
#' At a 1-year horizon, per within-state standard deviation, the ERA5-Land wind
#' measures come out ABOVE `maxs`. This script asks whether that is a real
#' finding about wind and mortality, or an artefact of how the two variables are
#' scaled and where their variation comes from.
#'
#' Six diagnostics, all on the 1-year window unless noted:
#'
#'   D1  Scaling arithmetic. What a "one standard deviation" move actually means
#'       for a spike train (`maxs`) versus an always-on series (ERA5-Land).
#'   D2  TC / non-TC decomposition. Split ERA5-Land into the part that lives in
#'       Young-Hsiang TC months and the part that lives everywhere else, and
#'       enter both. This is the direct test of whether the ERA5 signal is a
#'       tropical-cyclone signal at all.
#'   D3  Season decomposition. Same idea, splitting on TC season (Jun-Nov)
#'       versus the rest of the year.
#'   D4  No-TC-state placebo. Re-run ERA5-Land on the states that essentially
#'       never see a tropical cyclone, where `maxs` carries no information.
#'   D5  Leave-one-state-out. 36 refits per measure.
#'   D6  Leave-one-year-out. One refit per calendar year per measure.
#'
#' Inputs:  the panel and estimator defined in _wind_common.R
#' Outputs: output/data/wind_tc_validation/diag_*.csv
#'          output/figures/wind_tc_validation/diag_*.png
#'          output/tables/wind_tc_validation/diag_*.tex
#'
#' Run:  Rscript adhoc/wind_tc_validation/03_era5_diagnostics.R
#========================================================================================#

# Packages, panel, settings, variable construction and fit_dl() all live in
# _wind_common.R, which every analysis script in this directory sources.
.adhoc <- local({
  a <- grep("^--file=", commandArgs(FALSE), value = TRUE)
  d <- if (length(a) == 1) dirname(normalizePath(sub("^--file=", "", a))) else normalizePath(getwd())
  while (!file.exists(file.path(d, "_common.R")) && dirname(d) != d) d <- dirname(d)
  d
})
source(file.path(.adhoc, "_common.R"))
source(file.path(.adhoc, "wind_tc_validation", "_wind_common.R"))

suppressPackageStartupMessages(library(parallel))


L_D  <- L_YEAR                          # diagnostics run on the 1-year window
YMIN <- min(filter(d, !is.na(windmax_area_month))$year) + L_D / 12

#' Cumulative effect at the end of the lag window, one row per measure.
tail_of <- function(res, label) res$cum %>%
  filter(lag == max(lag)) %>%
  transmute(spec = label, measure, cum, cum_se, t = cum / cum_se,
            nobs, year_lo, year_hi)

# ---------------------------------------------------------------------------
# D1. What does "one standard deviation" mean for each measure?
# ---------------------------------------------------------------------------
message("\n=== D1. scaling arithmetic ===")
dd <- filter(d, year >= 1950)

scale_tab <- bind_rows(lapply(names(MEASURES), function(x) {
  v <- dd[[x]]
  tibble(measure = x,
             sd_within = SDS[x],
             share_pos = 100 * mean(v > 0),
             mean_pos  = mean(v[v > 0]),
             p99       = quantile(v, 0.99),
             # how large is a 1-SD move relative to a typical *event* in this
             # variable? for a spike train this ratio is small, because the SD is
             # generated by rare spikes rather than by routine variation
             sd_over_mean_pos = SDS[x] / mean(v[v > 0]))
}))
print(scale_tab)
write_csv(scale_tab, file.path(DIR_DATA, "diag_scaling.csv"))

fmt0 <- function(x, k = 2) formatC(x, format = "f", digits = k)
scale_rows <- vapply(c("maxs", "windmax_area_month", "w_exc"), function(x) {
  r <- filter(scale_tab, measure == x)
  sprintf("%s & %s & %s & %s & %s \\\\", MEASURES[x], fmt0(r$sd_within),
          fmt0(r$share_pos, 1), fmt0(r$mean_pos), fmt0(r$sd_over_mean_pos))
}, character(1))
writeLines(c("\\begin{tabular}{lcccc}", "\\toprule",
  " & Within-state & \\% of months & Mean when & SD $\\div$ mean \\\\",
  " & SD (m/s) & $>0$ & $>0$ (m/s) & when $>0$ \\\\", "\\midrule",
  scale_rows, "\\bottomrule", "\\end{tabular}"),
  file.path(DIR_TAB, "diag_scaling.tex"))

# ---------------------------------------------------------------------------
# D2. Is the ERA5 signal a tropical-cyclone signal?
# ---------------------------------------------------------------------------
# Split each ERA5 measure into two components that sum back to the original:
#   *_tc    the value in months Young and Hsiang record a TC (maxs > 0)
#   *_notc  the value in every other month
# Entered jointly, the two coefficients say where the mortality signal lives.
message("\n=== D2. TC / non-TC decomposition ===")

# The *_tc / *_notc columns are built once in _wind_common.R, by multiplication
# so that NA stays NA. They are deliberately NOT rebuilt here: an if_else()
# version would hand back a hard 0 for every pre-1950 row and defeat fit_dl()'s
# only guard against reaching back past the start of the ERA5 record.
message("  TC months: ", format(sum(dd$maxs > 0), big.mark = ","),
        " of ", format(nrow(dd), big.mark = ","),
        " (", round(100 * mean(dd$maxs > 0), 1), "%)")

d2 <- bind_rows(list(
  tail_of(fit_dl(c("windmax_area_month_tc", "windmax_area_month_notc"), L_D,
                 year_min = YMIN, label = "ERA5 raw split"), "ERA5 raw, split TC / non-TC"),
  tail_of(fit_dl(c("w_exc_tc", "w_exc_notc"), L_D,
                 year_min = YMIN, label = "ERA5 exceedance split"), "ERA5 exceedance, split TC / non-TC"),
  # for reference, maxs and the undivided ERA5 measures on the same sample
  tail_of(fit_dl("maxs", L_D, year_min = YMIN, label = "maxs"), "reference"),
  tail_of(fit_dl("windmax_area_month", L_D, year_min = YMIN, label = "ERA5 raw"), "reference"),
  tail_of(fit_dl("w_exc", L_D, year_min = YMIN, label = "ERA5 exceedance"), "reference")
))
print(d2)

# The user's requested variant: ERA5 forced to zero wherever the Young-Hsiang
# measure is (near) zero, entered on its own rather than alongside its complement.
d2_masked <- bind_rows(list(
  tail_of(fit_dl("windmax_area_month_tc", L_D, year_min = YMIN,
                 label = "ERA5 raw, zeroed outside TC months"), "masked"),
  tail_of(fit_dl("w_exc_tc", L_D, year_min = YMIN,
                 label = "ERA5 exceedance, zeroed outside TC months"), "masked"),
  tail_of(fit_dl("windmax_area_month_notc", L_D, year_min = YMIN,
                 label = "ERA5 raw, non-TC months only"), "masked"),
  tail_of(fit_dl("w_exc_notc", L_D, year_min = YMIN,
                 label = "ERA5 exceedance, non-TC months only"), "masked")
))
print(d2_masked)
write_csv(bind_rows(d2, d2_masked), file.path(DIR_DATA, "diag_tc_split.csv"))

# ---------------------------------------------------------------------------
# D3. Is it a season effect rather than a storm effect?
# ---------------------------------------------------------------------------
message("\n=== D3. season decomposition ===")
# maxs can be split this way as well, unlike the TC-month split (where maxs is
# what defines the split, so its complement is identically zero) and unlike the
# state split (only 9 TC months across the three no-TC states). Its off-season
# arm rests on 76 events, so it is thin.
d <- mutate(d, in_season = month %in% 6:11)
for (x in c("maxs", "windmax_area_month", "w_exc")) {
  # multiplication, not if_else(), for the same NA-preserving reason as above
  d[[paste0(x, "_seas")]] <- d[[x]] * as.numeric(d$in_season)
  d[[paste0(x, "_off")]]  <- d[[x]] * as.numeric(!d$in_season)
}

d3 <- bind_rows(list(
  tail_of(fit_dl(c("maxs_seas", "maxs_off"), L_D,
                 year_min = YMIN, label = "maxs, by season"), "maxs"),
  tail_of(fit_dl(c("windmax_area_month_seas", "windmax_area_month_off"), L_D,
                 year_min = YMIN, label = "ERA5 raw, by season"), "ERA5 raw"),
  tail_of(fit_dl(c("w_exc_seas", "w_exc_off"), L_D,
                 year_min = YMIN, label = "ERA5 exceedance, by season"), "ERA5 exceedance")
))
print(d3)
write_csv(d3, file.path(DIR_DATA, "diag_season.csv"))

# ---------------------------------------------------------------------------
# D4. Placebo: states that never see a tropical cyclone
# ---------------------------------------------------------------------------
# If ERA5-Land wind predicts mortality just as well in states with no TC
# exposure, the signal cannot be a tropical-cyclone signal.
message("\n=== D4. no-TC-state placebo ===")

# Left in stfips order, not sorted by share_tc: `no_tc` inherits this order and
# it is what the \placeboStates macro prints. (The original sorted afterwards
# and discarded the result, so the sort is simply dropped.)
tc_by_state <- dd %>%
  group_by(stfips, state_abbrev) %>%
  summarise(share_tc = mean(maxs > 0), mean_maxs = mean(maxs), .groups = "drop")
no_tc <- filter(tc_by_state, stfips %in% NO_TC_STATES)
message("  states with <1% TC months (n = ", nrow(no_tc), "): ",
        paste(no_tc$state_abbrev, collapse = ", "))

d4 <- bind_rows(list(
  tail_of(fit_dl("windmax_area_month", L_D, year_min = YMIN, est_filter = expr(stfips %in% !!no_tc$stfips),
                 label = "ERA5 raw, no-TC states"), "placebo: no-TC states"),
  tail_of(fit_dl("w_exc", L_D, year_min = YMIN, est_filter = expr(stfips %in% !!no_tc$stfips),
                 label = "ERA5 exceedance, no-TC states"), "placebo: no-TC states"),
  tail_of(fit_dl("maxs", L_D, year_min = YMIN, est_filter = expr(!stfips %in% !!no_tc$stfips),
                 label = "maxs, TC states"), "TC states"),
  tail_of(fit_dl("windmax_area_month", L_D, year_min = YMIN, est_filter = expr(!stfips %in% !!no_tc$stfips),
                 label = "ERA5 raw, TC states"), "TC states"),
  tail_of(fit_dl("w_exc", L_D, year_min = YMIN, est_filter = expr(!stfips %in% !!no_tc$stfips),
                 label = "ERA5 exceedance, TC states"), "TC states")
))
print(d4)
write_csv(d4, file.path(DIR_DATA, "diag_placebo.csv"))

# ---------------------------------------------------------------------------
# D5 / D6. Leave-one-state-out and leave-one-year-out
# ---------------------------------------------------------------------------
# est_filter drops the held-out unit from the estimation sample only, so the
# lag structure of the retained observations is untouched.
message("\n=== D5/D6. jackknife ===")

LOO_MEASURES <- c("maxs", "windmax_area_month", "w_exc")

loo_fit <- function(x, filt, dropped) {
  r <- try(tail_of(fit_dl(x, L_D, year_min = YMIN, est_filter = filt, label = x), "loo"),
           silent = TRUE)
  if (inherits(r, "try-error")) NULL else mutate(r, dropped = dropped)
}

states <- sort(unique(d$stfips))
abbrev <- distinct(d, stfips, state_abbrev)

LOO_KEY <- list(L = L_D, ymin = YMIN, measures = LOO_MEASURES)

loo_state <- cached("diag_loo_state", {
  r <- bind_rows(mclapply(states, function(s)
    bind_rows(lapply(LOO_MEASURES, function(x) loo_fit(x, expr(stfips != !!s), s))),
    mc.cores = N_CORES))
  inner_join(r, abbrev, by = c("dropped" = "stfips"))
}, key = LOO_KEY)

yrs <- d %>%
  filter(year >= YMIN, !is.na(.data[[OUTCOME]]), !is.na(tavg)) %>%
  pull(year) %>% unique() %>% sort()
loo_year <- cached("diag_loo_year",
  bind_rows(mclapply(yrs, function(y)
    bind_rows(lapply(LOO_MEASURES, function(x) loo_fit(x, expr(year != !!y), y))),
    mc.cores = N_CORES)), key = LOO_KEY)

# full-sample reference for each measure, to draw the baseline on the plots
# Cached under the SAME key as the jackknives: the deviations below are computed
# across the two, so a stale pairing would silently produce wrong percentages.
base <- cached("diag_baseline", bind_rows(lapply(LOO_MEASURES, function(x)
  tail_of(fit_dl(x, L_D, year_min = YMIN, label = x), "full"))), key = LOO_KEY)
# A failed fit would be silently dropped by rbindlist and then vanish from the
# figure, so assert the counts rather than trusting them.
stopifnot(nrow(loo_state) == length(states) * length(LOO_MEASURES),
          nrow(loo_year)  == length(yrs)    * length(LOO_MEASURES),
          nrow(base) == length(LOO_MEASURES))
message("  leave-one-out complete: ", nrow(loo_state), " state fits, ",
        nrow(loo_year), " year fits")

# ---------------------------------------------------------------------------
# D8. Do richer climate controls kill the ERA5 signal?
# ---------------------------------------------------------------------------
# The baseline already carries Young and Hsiang's temperature control, a
# state-specific quadratic in CONTEMPORANEOUS monthly mean temperature. That
# cannot absorb a delayed temperature effect, and mortality responds to
# temperature with a lag. So re-run each measure adding a full distributed lag in
# temperature over the same window - first in tavg, then in tavg and tavg^2.
# fit_dl already handles this: extra variables in `xs` simply enter as their own
# lag block. (tavg at lag 0 is spanned by the state-specific tavg slopes already
# in the fixed effects, so fixest drops it; lags 1..L are the new information.)
#
# NOTE ON PRECIPITATION: this panel carries no precipitation variable - the only
# climate fields in it are `tavg` and the ERA5-Land wind columns. Controlling for
# rainfall would mean building a state-month precipitation series from ERA5-Land
# on Midway with the same weights used for the wind merge. See the README.
message("\n=== D8. richer climate controls ===")

ctrl_specs <- list(
  `Young-Hsiang baseline`            = character(),
  `+ 12 lags of temperature`         = "tavg",
  `+ 12 lags of temperature and its square` = c("tavg", "tavg2")
)

d8 <- bind_rows(lapply(names(ctrl_specs), function(cs) {
  extra <- ctrl_specs[[cs]]
  bind_rows(lapply(c("maxs", "windmax_area_month", "w_exc"), function(x) {
    r <- fit_dl(c(x, extra), L_D, year_min = YMIN,
                label = sprintf("%s | %s", x, cs))
    tail_of(r, cs) %>%
      filter(measure == x) %>%          # drop the temperature rows
      mutate(control = cs)
  }))
}))
d8 <- mutate(d8, control = factor(control, levels = names(ctrl_specs)))
print(d8 %>% transmute(control, measure, cum = round(cum, 3),
                       se = round(cum_se, 3), t = round(t, 2)))
write_csv(d8, file.path(DIR_DATA, "diag_controls.csv"))

